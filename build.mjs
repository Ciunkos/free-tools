/* build.mjs: renders public/<path>.html for the hub and every live tool (EN, PL), copies each tool's client files to
   public/a/t/<id>/, writes the pre-built images, sitemap.xml (with image entries), llms.txt and the asset version.
   Lints every page (CSP, titles, "Przemo says", JSON-LD) and fails on any problem. node build.mjs */
import { writeFileSync, mkdirSync, readdirSync, readFileSync, statSync, copyFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname } from 'node:path';
import { STRONY, LANGS, BAZA, HUB, HUB_NAME, TOOLS, LIVE, ASSETY, sciezka } from './src/meta.mjs';

const bledy = [];
const zapisz = (plik, tresc) => { mkdirSync(dirname(plik), { recursive: true }); writeFileSync(plik, tresc); };

/* Routes: every page prefix must be covered by wrangler.toml. */
const wrangler = readFileSync('wrangler.toml', 'utf8');
for (const lang of LANGS) if (!wrangler.includes(`"ciunkos.com/${HUB[lang]}*"`)) bledy.push(`wrangler.toml: no route for /${HUB[lang]}*`);

/* Tool client files: tools/<id>/* except page.mjs, copied to public/a/t/<id>/. */
for (const id of LIVE) for (const f of readdirSync('tools/' + id)) {
  if (f === 'page.mjs') continue;
  mkdirSync('public/a/t/' + id, { recursive: true });
  copyFileSync(`tools/${id}/${f}`, `public/a/t/${id}/${f}`);
}

/* Shared footer CSS, generated from the synced copy. */
const { SITE_FOOTER_CSS } = await import('./src/shared/site-footer.mjs');
zapisz('public/a/site-footer.css', '/* GENERATED by build.mjs from src/shared/site-footer.mjs. Do not edit. */\n' + SITE_FOOTER_CSS + '\n');

/* Pre-built white images (real files for image search and plain links). */
const { solidPng, PRESETS, fileName } = await import('./tools/white-screen/png.mjs');
for (const p of PRESETS.filter((x) => x.prebuilt)) {
  const plik = 'public/a/img/' + fileName(p.w, p.h);
  if (!existsSync(plik)) zapisz(plik, await solidPng(p.w, p.h));
}

/* Our own 10-hour white videos (ffmpeg, only when missing; verified pure white). */
const { ensureVideos } = await import('./scripts/videos.mjs');
const filmy = ensureVideos();

/* Asset version: hash of everything under public/a (except generated images). */
const h = createHash('sha256');
const chodz = (d) => { for (const f of readdirSync(d).sort()) { const p = d + '/' + f; if (statSync(p).isDirectory()) { if (p !== 'public/a/img' && p !== 'public/a/video') chodz(p); } else if (/\.(css|mjs|js|webp|png|jpg|svg|webmanifest)$/.test(f)) h.update(p).update(readFileSync(p)); } };
const { manifest } = await import('./tools/white-screen/page.mjs');
for (const lang of LANGS) zapisz(`public/a/t/white-screen/manifest-${lang}.webmanifest`, manifest(lang) + '\n');
chodz('public/a');
const WERSJA = new Date().toISOString().slice(0, 10) + '-' + h.digest('hex').slice(0, 7);
writeFileSync('src/wersja.mjs', `/* GENERATED by build.mjs. Do not edit. */\nexport const WERSJA = '${WERSJA}';\n/* Video sizes in bytes, for Range answers (the assets binding does not always send Content-Length). */\nexport const ROZMIARY = ${JSON.stringify(Object.fromEntries(filmy.map((f) => ['/video/' + f.file, f.bytes])))};\n`);

const { lintHtml, lintLd } = await import('./src/lint.mjs');
const { ulepszLd } = await import('./src/shared/schema-ld.mjs');
const { zmiana, publikacja } = await import('./src/shared/daty.mjs');
const RENDER = { hub: (await import('./src/hub.mjs')).renderHub };
for (const id of LIVE) RENDER[id] = (await import(`./tools/${id}/page.mjs`)).render;

/* Content dates from git: the last commit touching the page's copy (tool folder, or the hub + registry). */
const zrodla = (id) => (id === 'hub' ? ['src/hub.mjs', 'src/meta.mjs'] : ['tools/' + id + '/page.mjs']);
const lastmod = {};
for (const s of STRONY) for (const lang of LANGS) {
  const modified = zmiana(...zrodla(s.id));
  const html = RENDER[s.id]({ lang, wersja: WERSJA, updated: modified });
  bledy.push(...lintHtml(html, s.path[lang], { tool: s.id !== 'hub' }));
  const out = ulepszLd(html, { modified, published: publikacja(zrodla(s.id)[0]), lang });
  bledy.push(...lintLd(out, s.path[lang]));
  lastmod[s.path[lang]] = modified;
  zapisz('public/' + s.path[lang] + '.html', out);
}

const obrazy = (s, lang) => (s.id === 'white-screen' ? PRESETS.filter((p) => p.prebuilt).map((p) => `
    <image:image><image:loc>${BAZA}${ASSETY}/img/${fileName(p.w, p.h)}</image:loc></image:image>`).join('') : '');
zapisz('public/sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${STRONY.flatMap((s) => LANGS.map((lang) => `  <url>
    <loc>${BAZA}/${s.path[lang]}</loc>
    <lastmod>${lastmod[s.path[lang]]}</lastmod>
    <xhtml:link rel="alternate" hreflang="en" href="${BAZA}/${s.path.en}"/>
    <xhtml:link rel="alternate" hreflang="pl" href="${BAZA}/${s.path.pl}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${BAZA}/${s.path.en}"/>${obrazy(s, lang)}
  </url>`)).join('\n')}
</urlset>
`);

const LLMS = {
  'white-screen': `A totally white (#FFFFFF) page that goes full screen with one click or the F key; Esc exits. For cleaning a monitor or TV and seeing every speck, checking for dead or stuck pixels and backlight bleed, or as a light for video calls, make-up and tracing. Shades: pure, warm, cool, dimmed. Keeps the screen awake in full screen (Screen Wake Lock). On iPhone, Add to Home Screen gives edge-to-edge white. Also downloads pure white PNGs of any size up to 16,384 px a side, generated in the browser (ready-made: 1920×1080, 3840×2160, 1179×2556, A4 at 300 dpi), and its own 10-hour pure white video (MP4, 1080p and 4K, CC0): ${BAZA}${ASSETY}/video/white-screen-10-hours-1080p.mp4. On iPhone, where Safari allows only videos to go full screen, the Full screen button plays that video full screen.`
};
zapisz('public/llms.txt', `# ${HUB_NAME.en} by Przemysław Zalewski (ciunkos.com)

> Small free browser tools, each built for a problem the author had himself. Free, no sign-up, no ads; tool input never leaves the browser.

- Directory: ${BAZA}/${HUB.en} (Polish: ${BAZA}/${HUB.pl})
${LIVE.map((id) => `- ${TOOLS[id].name.en}: ${BAZA}/${sciezka(id, 'en')} (Polish: ${BAZA}/${sciezka(id, 'pl')}). ${LLMS[id] || TOOLS[id].pain.en}`).join('\n')}
- Author: ${BAZA}/hire-me (hire), ${BAZA}/about
`);

if (bledy.length) { console.error('LINT: ' + bledy.length + ' problem(s)'); for (const b of bledy) console.error(' - ' + b); process.exit(1); }
console.log('OK: ' + STRONY.length * 2 + ' pages, version ' + WERSJA);
